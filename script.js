// State
let currentImageIndex = 0;
let currentGroupImages = [];

// DOM Elements
const navbar = document.getElementById('navbar');
const mobileMenuBtn = document.getElementById('mobileMenuBtn');
const mobileMenu = document.getElementById('mobileMenu');
const navLinks = document.querySelectorAll('.nav-link');
const mobileLinks = document.querySelectorAll('.mobile-link');
const designGrid = document.getElementById('designGrid');
const viewMoreBtn = document.getElementById('viewMoreBtn');
const designModal = document.getElementById('designModal');
const modalCloseBtn = document.getElementById('modalCloseBtn');
const modalBody = document.getElementById('modalBody');
const imageViewer = document.getElementById('imageViewer');
const viewerCloseBtn = document.getElementById('viewerCloseBtn');
const viewerPrevBtn = document.getElementById('viewerPrevBtn');
const viewerNextBtn = document.getElementById('viewerNextBtn');
const viewerImage = document.getElementById('viewerImage');
const viewerCounter = document.getElementById('viewerCounter');

// Navbar scroll effect
window.addEventListener('scroll', () => {
    if (window.scrollY > 50) {
        navbar.classList.add('scrolled');
    } else {
        navbar.classList.remove('scrolled');
    }

    // Update active nav link based on scroll position
    const sections = document.querySelectorAll('section');
    let current = '';

    sections.forEach(section => {
        const sectionTop = section.offsetTop;
        const sectionHeight = section.clientHeight;
        if (window.scrollY >= sectionTop - 100) {
            current = section.getAttribute('id');
        }
    });

    navLinks.forEach(link => {
        link.classList.remove('active');
        if (link.getAttribute('href') === `#${current}`) {
            link.classList.add('active');
        }
    });
});

// Mobile menu toggle
mobileMenuBtn.addEventListener('click', () => {
    mobileMenu.classList.toggle('active');
});

// Close mobile menu when clicking a link
mobileLinks.forEach(link => {
    link.addEventListener('click', () => {
        mobileMenu.classList.remove('active');
    });
});

// Smooth scrolling for nav links
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function (e) {
        e.preventDefault();
        const target = document.querySelector(this.getAttribute('href'));
        if (target) {
            target.scrollIntoView({
                behavior: 'smooth',
                block: 'start'
            });
        }
    });
});

// Create design card HTML
function createDesignCard(work, index) {
    return `
        <div class="design-card" data-index="${index}">
            <div class="design-image">
                <img src="${work.image}" alt="${work.title}">
                <div class="design-overlay">
                    <div class="design-overlay-text">Click to View</div>
                </div>
                ${work.groupImages.length > 1 ? `<div class="design-badge">+${work.groupImages.length}</div>` : ''}
            </div>
            <div class="design-content">
                <div class="design-header">
                    <h3>${work.title}</h3>
                </div>
                <p class="design-type">${work.type}</p>
                <p class="design-org"> ${work.organization}</p>
            </div>
        </div>
    `;
}

// Render initial design works
function renderDesignWorks() {
    designGrid.innerHTML = designWorks.map((work, index) => createDesignCard(work, index)).join('');
    
    // Add click listeners
    document.querySelectorAll('.design-card').forEach((card, index) => {
        card.addEventListener('click', () => {
            openImageViewer(designWorks[index].groupImages, 0);
        });
    });
}

// Render all design works in modal
function renderAllDesignWorks() {
    const modalGrid = document.createElement('div');
    modalGrid.className = 'modal-grid';
    modalGrid.innerHTML = allDesignWorks.map((work, index) => createDesignCard(work, index)).join('');
    modalBody.innerHTML = '';
    modalBody.appendChild(modalGrid);
    
    // Add click listeners
    modalBody.querySelectorAll('.design-card').forEach((card, index) => {
        card.addEventListener('click', () => {
            openImageViewer(allDesignWorks[index].groupImages, 0);
            closeModal();
        });
    });
}

// Open image viewer
function openImageViewer(images, index) {
    currentGroupImages = images;
    currentImageIndex = index;
    viewerImage.src = images[index];
    updateViewerCounter();
    imageViewer.classList.add('active');
    document.body.style.overflow = 'hidden';
    
    // Show/hide navigation buttons
    if (images.length <= 1) {
        viewerPrevBtn.style.display = 'none';
        viewerNextBtn.style.display = 'none';
        viewerCounter.style.display = 'none';
    } else {
        viewerPrevBtn.style.display = 'flex';
        viewerNextBtn.style.display = 'flex';
        viewerCounter.style.display = 'block';
    }
}

// Close image viewer
function closeImageViewer() {
    imageViewer.classList.remove('active');
    document.body.style.overflow = '';
    currentGroupImages = [];
    currentImageIndex = 0;
}

// Navigate to previous image
function previousImage() {
    if (currentGroupImages.length > 0) {
        currentImageIndex = currentImageIndex === 0 
            ? currentGroupImages.length - 1 
            : currentImageIndex - 1;
        viewerImage.src = currentGroupImages[currentImageIndex];
        updateViewerCounter();
    }
}

// Navigate to next image
function nextImage() {
    if (currentGroupImages.length > 0) {
        currentImageIndex = (currentImageIndex + 1) % currentGroupImages.length;
        viewerImage.src = currentGroupImages[currentImageIndex];
        updateViewerCounter();
    }
}

// Update viewer counter
function updateViewerCounter() {
    if (currentGroupImages.length > 1) {
        viewerCounter.textContent = `${currentImageIndex + 1} / ${currentGroupImages.length}`;
    }
}

// Open modal
function openModal() {
    renderAllDesignWorks();
    designModal.classList.add('active');
    document.body.style.overflow = 'hidden';
}

// Close modal
function closeModal() {
    designModal.classList.remove('active');
    document.body.style.overflow = '';
}

// Event listeners
viewMoreBtn.addEventListener('click', openModal);
modalCloseBtn.addEventListener('click', closeModal);
viewerCloseBtn.addEventListener('click', closeImageViewer);
viewerPrevBtn.addEventListener('click', previousImage);
viewerNextBtn.addEventListener('click', nextImage);

// Close modal when clicking outside
designModal.addEventListener('click', (e) => {
    if (e.target === designModal) {
        closeModal();
    }
});

// Close image viewer when clicking outside
imageViewer.addEventListener('click', (e) => {
    if (e.target === imageViewer) {
        closeImageViewer();
    }
});

// Keyboard navigation for image viewer
document.addEventListener('keydown', (e) => {
    if (imageViewer.classList.contains('active')) {
        if (e.key === 'ArrowLeft') {
            previousImage();
        } else if (e.key === 'ArrowRight') {
            nextImage();
        } else if (e.key === 'Escape') {
            closeImageViewer();
        }
    }
    
    if (designModal.classList.contains('active') && e.key === 'Escape') {
        closeModal();
    }
});

// Initialize
renderDesignWorks();

// Animate skill bars on scroll
const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.style.opacity = '1';
            entry.target.style.transform = 'translateY(0)';
        }
    });
}, {
    threshold: 0.1
});

// Observe all sections for animation
document.querySelectorAll('section').forEach(section => {
    section.style.opacity = '0';
    section.style.transform = 'translateY(20px)';
    section.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
    observer.observe(section);
});
